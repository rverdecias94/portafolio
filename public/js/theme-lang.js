function tFactory(getLang) {
  return (key) => {
    const lang = getLang();
    return I18N[lang]?.[key] ?? I18N.es[key] ?? key;
  };
}

function applyI18n(root, t) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const label = t(el.getAttribute("data-i18n-aria"));
    el.setAttribute("aria-label", label);
    el.setAttribute("title", label);
  });
  root.querySelectorAll("option[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
}

function initThemeLang({ onLang } = {}) {
  const root = document.documentElement;
  const body = document.body;

  const getLang = () => (root.getAttribute("lang") === "en" ? "en" : "es");
  const t = tFactory(getLang);

  const setLang = (lang) => {
    const next = lang === "en" ? "en" : "es";
    root.setAttribute("lang", next);
    try {
      localStorage.setItem("lang", next);
    } catch (_) {
      /* private mode */
    }
    applyI18n(document, t);
    document.querySelectorAll("[data-lang-toggle]").forEach((btn) => {
      const mark = btn.querySelector("[data-lang-mark]");
      if (mark) mark.textContent = next === "es" ? "EN" : "ES";
    });
    onLang?.(next, t);
  };

  const setTheme = (dark) => {
    body.classList.toggle("theme-obsidian", Boolean(dark));
    try {
      localStorage.setItem("theme", dark ? "dark" : "light");
    } catch (_) {
      /* private mode */
    }
    const label = t(dark ? "theme_to_light" : "theme_to_dark");
    document.querySelectorAll("[data-theme-toggle]").forEach((btn) => {
      btn.setAttribute("aria-label", label);
      btn.setAttribute("title", label);
      btn.setAttribute("aria-pressed", String(Boolean(dark)));
    });
  };

  let savedLang = null;
  let savedTheme = null;
  try {
    savedLang = localStorage.getItem("lang");
    savedTheme = localStorage.getItem("theme");
  } catch (_) {
    /* private mode */
  }
  const prefersDark = window.matchMedia?.("(prefers-color-scheme: dark)").matches;
  setLang(savedLang === "en" ? "en" : "es");
  setTheme(savedTheme ? savedTheme === "dark" : Boolean(prefersDark));

  document.querySelectorAll("[data-lang-toggle]").forEach((btn) => {
    btn.addEventListener("click", () => setLang(getLang() === "es" ? "en" : "es"));
  });
  document.querySelectorAll("[data-theme-toggle]").forEach((btn) => {
    btn.addEventListener("click", () => setTheme(!body.classList.contains("theme-obsidian")));
  });

  return { getLang, t, setLang, setTheme };
}

window.RVLang = { I18N, tFactory, applyI18n, initThemeLang };
